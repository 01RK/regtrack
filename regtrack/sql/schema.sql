    source_page      TEXT,
    review_status    TEXT,
    confidence       TEXT,
    needs_review     TEXT,
    import_key       VARCHAR(255) NOT NULL,
    CONSTRAINT uq_chapter_clause UNIQUE (import_batch_id, clause_no),
    CONSTRAINT uq_chapter_sequence UNIQUE (import_batch_id, sequence),
    CONSTRAINT uq_chapter_key UNIQUE (import_batch_id, import_key)
