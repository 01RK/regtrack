
CREATE TABLE app_meta (
    schema_version INTEGER NOT NULL
);

CREATE TABLE lookup_value (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_lookup_value PRIMARY KEY,
    category   VARCHAR(50) NOT NULL,
    value    VARCHAR(255) NOT NULL,
    note     TEXT,
    sort_order INTEGER NOT NULL,
    is_active  INTEGER NOT NULL,
    CONSTRAINT uq_lookup_value UNIQUE (category, value)
);

CREATE TABLE standard (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_standard PRIMARY KEY,
    std_no                VARCHAR(255),
    plan_no               VARCHAR(100),
    name_cn               TEXT NOT NULL,
    name_en               TEXT,
    stage_code            VARCHAR(30) NOT NULL,
    std_type              VARCHAR(20),
    tc_wg                 VARCHAR(255),
    responsible_authority VARCHAR(255),
    leading_org           VARCHAR(255),
    risk_level            VARCHAR(10),
    mb_owner              VARCHAR(255),
    planned_release_date  VARCHAR(10),
    actual_release_date   VARCHAR(10),
    effective_date        VARCHAR(10),
    scope                 TEXT,
    archived_at           VARCHAR(19),
    archived_by           VARCHAR(255),
    created_at            VARCHAR(19) NOT NULL,
    created_by            VARCHAR(255),
    updated_at            VARCHAR(19) NOT NULL,
    updated_by            VARCHAR(255)
);
CREATE INDEX ix_standard_std_no ON standard (std_no);
CREATE INDEX ix_standard_archived ON standard (archived_at);

CREATE TABLE standard_impact_area (
    standard_id INTEGER NOT NULL CONSTRAINT fk_impact_standard REFERENCES standard (id) ON DELETE CASCADE,
    impact_area VARCHAR(255) NOT NULL,
    CONSTRAINT pk_standard_impact_area PRIMARY KEY (standard_id, impact_area)
);

CREATE TABLE standard_stage_history (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_standard_stage_history PRIMARY KEY,
    standard_id    INTEGER NOT NULL CONSTRAINT fk_stage_standard REFERENCES standard (id) ON DELETE CASCADE,
