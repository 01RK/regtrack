CREATE TABLE draft (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_draft PRIMARY KEY,
    standard_id    INTEGER NOT NULL CONSTRAINT fk_draft_standard REFERENCES standard (id) ON DELETE CASCADE,
    version_name   VARCHAR(20) NOT NULL,
    sub_version_no VARCHAR(50) NOT NULL,
    draft_date     VARCHAR(10) NOT NULL,
    file_link      TEXT,
    issued_by      VARCHAR(255),
    main_summary   TEXT,
    overall_impact VARCHAR(20),
    notes          TEXT,
    created_at     VARCHAR(19) NOT NULL,
    created_by     VARCHAR(255),
    updated_at     VARCHAR(19) NOT NULL,
    updated_by     VARCHAR(255),
    CONSTRAINT uq_draft_version UNIQUE (standard_id, version_name, sub_version_no)
);

CREATE TABLE draft_import (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_draft_import PRIMARY KEY,
    draft_id             INTEGER NOT NULL CONSTRAINT fk_import_draft REFERENCES draft (id) ON DELETE CASCADE,
    filename             VARCHAR(255) NOT NULL,
    source_version       TEXT NOT NULL,
    source_standard_no   TEXT NOT NULL,
    source_standard_name TEXT NOT NULL,
    created_at           VARCHAR(19) NOT NULL,
    created_by           VARCHAR(255) NOT NULL
);

CREATE TABLE draft_chapter (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_draft_chapter PRIMARY KEY,
    draft_id         INTEGER NOT NULL,
    import_batch_id  INTEGER NOT NULL CONSTRAINT fk_chapter_import REFERENCES draft_import (id) ON DELETE CASCADE,
    clause_no        VARCHAR(255) NOT NULL,
    parent_clause_no VARCHAR(255) NOT NULL,
    level          INTEGER NOT NULL,
    sequence       INTEGER NOT NULL,
    title_cn         TEXT,
